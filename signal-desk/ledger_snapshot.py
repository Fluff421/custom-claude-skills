"""Regenerate signal-desk/LEDGER.md and the ledger block of data/snapshot.json
from the Airtable Signal Desk Ledger (graded Game rows only).

The daily digest snapshot was writing a hand-built "empty ledger" even after
close_grade.py had graded picks. This script makes the ledger snapshot a pure
function of Airtable so it cannot drift.

Usage:
  python signal-desk/ledger_snapshot.py                 # reads Airtable (AIRTABLE_TOKEN, AIRTABLE_BASE_ID)
  python signal-desk/ledger_snapshot.py --from-json F   # offline: F is a JSON list of Airtable records
"""
from __future__ import annotations

import datetime as dt
import json
import os
import sys
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
LEDGER_TABLE = "tbl3tFHFhvyNMpksE"
LEDGER_MD = os.path.join(HERE, "LEDGER.md")
SNAPSHOT = os.path.join(HERE, "data", "snapshot.json")
GRADES = ("Win", "Loss", "Push")
TIERS = ("Max Play", "Strong Play", "Lean")
MIN_SAMPLE = 30


def fetch_airtable() -> list[dict]:
    sys.path.insert(0, HERE)
    import espn_sync as es

    token = os.environ.get("AIRTABLE_TOKEN", "").strip()
    base = os.environ.get("AIRTABLE_BASE_ID", "").strip()
    if not (token and base):
        raise SystemExit("ERROR: AIRTABLE_TOKEN and AIRTABLE_BASE_ID must be set.")
    formula = "AND({Record Type}='Game',OR({Grade}='Win',{Grade}='Loss',{Grade}='Push'))"
    out, offset = [], None
    while True:
        url = (f"https://api.airtable.com/v0/{base}/{LEDGER_TABLE}?pageSize=100&filterByFormula="
               + urllib.parse.quote(formula))
        if offset:
            url += "&offset=" + urllib.parse.quote(offset, safe="")
        page = json.loads(es.http_get(url, es.at_headers(token)))
        out.extend(page.get("records", []))
        offset = page.get("offset")
        if not offset:
            return out


def market(side: str) -> str:
    s = (side or "").lower()
    if "(total)" in s or s.startswith(("over ", "under ")):
        return "totals"
    if "(ml)" in s or "moneyline" in s:
        return "ml"
    return "ats"


def blank() -> dict:
    return {"hits": 0, "misses": 0, "pushes": 0, "units": 0.0}


def add(t: dict, grade: str, units: float) -> None:
    if grade == "Win":
        t["hits"] += 1
        t["units"] += units  # Splash lines are even money
    elif grade == "Loss":
        t["misses"] += 1
        t["units"] -= units
    else:
        t["pushes"] += 1


def rec(t: dict) -> str:
    n = t["hits"] + t["misses"] + t["pushes"]
    dec = t["hits"] + t["misses"]
    pct = f"{t['hits'] / dec:.1%}" if dec else "n/a"
    return f"{t['hits']}-{t['misses']}-{t['pushes']} (n={n}, {pct}, {t['units']:+.1f}u)"


def build(records: list[dict], today: str) -> tuple[str, dict]:
    rows = [r["fields"] for r in records
            if r.get("fields", {}).get("Grade") in GRADES
            and r["fields"].get("Record Type", "Game") == "Game"]
    rows.sort(key=lambda f: (f.get("Date", ""), f.get("Game", "")))

    mk = {k: blank() for k in ("ats", "ml", "totals")}
    tiers = {k: blank() for k in TIERS}
    leagues: dict[str, dict] = {}
    overall = blank()
    clv = []
    for f in rows:
        g, u = f["Grade"], float(f.get("Sharp-Sheet Suggested Units") or 0)
        add(mk[market(f.get("Recommended Side", ""))], g, u)
        add(overall, g, u)
        if f.get("Sharp-Sheet Tier") in tiers:
            add(tiers[f["Sharp-Sheet Tier"]], g, u)
        add(leagues.setdefault(f.get("League", "?"), blank()), g, u)
        if isinstance(f.get("Sharp-Sheet CLV Points"), (int, float)):
            clv.append(f["Sharp-Sheet CLV Points"])

    n = len(rows)
    L = ["# Signal Desk Ledger", "",
         f"As of {today}. Generated by `signal-desk/ledger_snapshot.py` from the Airtable "
         "Signal Desk Ledger (graded Game rows). Do not edit by hand.", ""]
    if not n:
        L += ["No graded 2026 picks yet.", ""]
    L += ["## Record", "",
          f"- Overall: {rec(overall)}",
          f"- ATS: {rec(mk['ats'])}",
          f"- ML: {rec(mk['ml'])}",
          f"- Totals: {rec(mk['totals'])}"]
    if clv:
        L.append(f"- Avg CLV: {sum(clv) / len(clv):+.2f} pts (n={len(clv)})")
    L += ["", "## By tier", ""] + [f"- {k}: {rec(tiers[k])}" for k in TIERS]
    L += ["", "## By league", ""] + [f"- {k}: {rec(v)}" for k, v in sorted(leagues.items())]
    if n:
        L += ["", "## Graded picks", "",
              "| Date | League | Game | Tier | Pick | Units | Final (A-H) | Grade | CLV |",
              "|---|---|---|---|---|---|---|---|---|"]
        for f in rows:
            final = f"{f.get('Away Score', '')}-{f.get('Home Score', '')}"
            L.append(f"| {f.get('Date', '')} | {f.get('League', '')} | {f.get('Game', '')} | "
                     f"{f.get('Sharp-Sheet Tier', '')} | {f.get('Recommended Side', '')} | "
                     f"{f.get('Sharp-Sheet Suggested Units', '')} | {final} | {f['Grade']} | "
                     f"{f.get('Sharp-Sheet CLV Points', '')} |")
    L += ["", f"Flag: n < {MIN_SAMPLE} — sample too small for calibration or unit sizing changes."
          if n < MIN_SAMPLE else f"Sample n={n} (>= {MIN_SAMPLE})."]
    ledger = {k: {x: v[x] for x in ("hits", "misses", "pushes")} for k, v in mk.items()}
    return "\n".join(L) + "\n", ledger


def main() -> None:
    args = sys.argv[1:]
    if args[:1] == ["--from-json"]:
        with open(args[1]) as fh:
            records = json.load(fh)
    else:
        records = fetch_airtable()
    from zoneinfo import ZoneInfo
    today = dt.datetime.now(ZoneInfo("America/Chicago")).date().isoformat()
    md, ledger = build(records, today)
    with open(LEDGER_MD, "w") as fh:
        fh.write(md)
    snap = {}
    if os.path.exists(SNAPSHOT):
        with open(SNAPSHOT) as fh:
            snap = json.load(fh)
    snap["ledger"] = ledger
    snap["ledger_updated"] = today
    if "No prior graded" in snap.get("notes", "") and any(sum(v.values()) for v in ledger.values()):
        snap["notes"] = "Ledger regenerated from Airtable graded rows. Ensemble weight 0."
    with open(SNAPSHOT, "w") as fh:
        json.dump(snap, fh)
        fh.write("\n")
    print(md)


if __name__ == "__main__":
    main()
